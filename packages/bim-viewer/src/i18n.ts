const TEXTS: Record<ViewerLanguage, Record<Key, string>> = { en, tr };

let current: ViewerLanguage = "tr";

/** Sets the language of the viewer texts: "tr…" is Turkish, anything else English. */
export function setViewerLanguage(lang: string | null | undefined): ViewerLanguage {
  current = lang?.toLowerCase().startsWith("tr") ? "tr" : "en";
  return current;
}

export function viewerLanguage(): ViewerLanguage {
  return current;
}

/** A viewer text in the current language; `{{name}}` is replaced from params. */
export function vt(key: Key, params?: Record<string, string | number>): string {
  const text = TEXTS[current][key] ?? en[key];
  return params ? text.replace(/\{\{(\w+)\}\}/g, (m, k: string) => (k in params ? String(params[k]) : m)) : text;
}

export type ViewerTextKey = Key;
