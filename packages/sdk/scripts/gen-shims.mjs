// Writes server.js / web.js / shared.js: one named export per value the core's SDK (and
// packages/shared) exports, read from the object the core binds
// before it loads modules (apps/*/src/sdk/bind.ts). `--check` fails when a shim is out of date.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const pkg = path.resolve(here, "..");
const root = path.resolve(pkg, "../..");
const check = process.argv.includes("--check");

/** Value (non-type) names exported by a TS file, following `export * from "./x.js"`. */
export function valueExports(file) {
  const src = readFileSync(file, "utf8").replace(/\/\*[\s\S]*?\*\/|\/\/[^\n]*/g, "");
  const names = [];
  // `export { a, b as c } from "./x.js"` and the local `export { a, b as c };`
  for (const m of src.matchAll(/export\s+(type\s+)?\{([^}]*)\}/g)) {
    if (m[1]) continue;
    for (const raw of m[2].split(",")) {
      const s = raw.trim();
      if (!s || s.startsWith("type ")) continue;
      names.push(s.split(/\s+as\s+/).pop());
    }
  }
  for (const m of src.matchAll(/export\s+\*\s+from\s+"([^"]+)"/g)) {
    const target = path.resolve(path.dirname(file), m[1].replace(/\.js$/, ".ts"));
    names.push(...valueExports(target));
  }
  for (const m of src.matchAll(/export\s+(?:const|function|class|let)\s+(\w+)/g)) names.push(m[1]);
  return [...new Set(names)].sort();
}

const SIDES = [
  { side: "server", entry: "apps/server/src/sdk/index.ts", refs: ['path="./types/apps/server/src/previews/dxf-viewer-src.d.ts"'] },
  { side: "web", entry: "apps/web/src/sdk/index.ts", refs: ['path="./types/apps/web/src/i18n/i18next.d.ts"', 'types="vite/client"'] },
  { side: "shared", entry: "packages/shared/src/index.ts", refs: [] },
];

let stale = false;
for (const { side, entry, refs } of SIDES) {
  const names = valueExports(path.join(root, entry));
  const key = `sitekeep.sdk.${side}`;
  const js = `// Generated by scripts/gen-shims.mjs from ${entry}. Do not edit.
// The core binds its SDK to globalThis[Symbol.for("${key}")] before it loads any module.
const core = globalThis[Symbol.for("${key}")];
if (!core) throw new Error("@7dimensions-project/sitekeep-sdk/${side}: the SiteKeep core has not bound its SDK; modules run inside the core.");
export const {
${names.map((n) => `  ${n},`).join("\n")}
} = core;
`;
  const dts = `// Generated by scripts/gen-shims.mjs. Declarations of ${entry}, emitted into types/ by
// scripts/build-types.mjs (docs/modules/README.md).
${refs.map((r) => `/// <reference ${r} />\n`).join("")}export * from "./types/${entry.replace(/\.ts$/, ".js")}";
`;
  for (const [name, text] of [[`${side}.js`, js], [`${side}.d.ts`, dts]]) {
    const file = path.join(pkg, name);
    let old = "";
    try {
      old = readFileSync(file, "utf8");
    } catch {}
    if (old === text) continue;
    if (check) {
      console.error(`${name} is out of date: run npm run build -w @7dimensions-project/sitekeep-sdk`);
      stale = true;
    } else writeFileSync(file, text);
  }
}
if (stale) process.exit(1);
